import { test } from 'node:test';
import assert from 'node:assert/strict';
import { advance, createGame, dispatch } from './simulation';
import { scheduleTransfer } from './orders';
import { resign } from './retirement';
import { setFunding } from './funding';
import { observe } from './visibility';

test('resignation stops orders, cargo, mining, and funding while retaining territory, forces, production, shields, and sonar', () => {
  let game = createGame(0);
  game.cargo = { you: 40, vesper: 20, null: 0 };
  game = setFunding(game, 'you', 'vesper', true);
  game = setFunding(game, 'vesper', 'null', true);
  const mine = game.rocks.find(r => r.id === 'm')!;
  mine.kind = 'mine'; mine.miningAt = 1; mine.miningInterval = 24 / 5;
  game = dispatch(game, 'c', 'b', 10, 'you');
  game = advance(game, 0.2, { rivals: false });
  game = dispatch(game, 'n', 'o', 5, 'you');
  game = scheduleTransfer(game, { id: 'retirement-future-001', owner: 'you', from: 'o', to: 'n', drones: 1, executeAt: 3 });
  const before = JSON.stringify(game);
  const retired = resign(game, 'you');
  assert.equal(JSON.stringify(game), before);
  assert.deepEqual(retired.eliminated, ['you']);
  assert.equal(retired.cargo.you, 0);
  assert.equal(retired.funding!.some(f => f.from === 'you' || f.to === 'you'), false);
  assert.equal(retired.funding!.some(f => f.from === 'vesper' && f.to === 'null'), true);
  assert.equal(retired.scheduled!.length, 0);
  assert.equal(retired.rocks.filter(r => r.owner === 'you').length, 5);
  assert.equal(retired.fleets.find(f => !f.preparing)!.drones, 10);
  assert.equal(retired.fleets.some(f => f.preparing), false);
  assert.equal(retired.rocks.find(r => r.id === 'n')!.drones, 40);
  const after = advance(retired, 16, { rivals: false });
  assert.equal(after.cargo.you, 0);
  assert.ok(after.rocks.find(r => r.id === 'a')!.drones > retired.rocks.find(r => r.id === 'a')!.drones);
  assert.ok(after.rocks.find(r => r.id === 'a')!.shield! > retired.rocks.find(r => r.id === 'a')!.shield!);
  assert.ok(after.rocks.some(r => r.id === 'b' && r.owner === 'you'));
  assert.deepEqual(observe(retired, 'you').coverage, observe(game, 'you').coverage);
  assert.throws(() => dispatch(retired, 'n', 'o', 1, 'you'), /no longer/);
});

test('retirement replays at its real submission time and simultaneous inactivity cannot award a spurious winner', async () => {
  const { applyCommand, createArchive, replayTo, exportArchive } = await import('./replay');
  const { decodeReplay } = await import('./replay-save');
  const start = createGame(0);
  const first = applyCommand(createArchive(start), { type: 'resign', owner: 'vesper' }, { rivals: false, knownThrough: 2 });
  assert.equal(first.game.winner, null);
  assert.deepEqual(replayTo(first.archive, 1, { rivals: false, knownThrough: 2 }).eliminated, []);
  const both = applyCommand(first.archive, { type: 'inactivity', owners: ['you', 'null'] }, { rivals: false, knownThrough: 48 });
  assert.equal(both.game.draw, true);
  assert.equal(both.game.winner, null);
  assert.equal(both.game.eliminated.length, 3);
  assert.deepEqual(replayTo(decodeReplay(JSON.parse(JSON.stringify(exportArchive(both.archive))), both.game, false), 48, { rivals: false, knownThrough: 48 }), both.game);
  assert.throws(() => applyCommand(createArchive(start, { rivals: true }), { type: 'inactivity', owners: ['you'] }, { rivals: true, knownThrough: 48 }), /Automatic|server/);
  assert.throws(() => applyCommand(first.archive, { type: 'resign', owner: 'vesper' }, { rivals: false, knownThrough: 2 }), /active/);
  assert.throws(() => decodeReplay({ ...exportArchive(both.archive), entries: [{ hour: 48, command: { type: 'inactivity', owners: ['you', 'you'] } }] }, both.game, false));
  const last = applyCommand(first.archive, { type: 'resign', owner: 'null' }, { rivals: false, knownThrough: 4 });
  assert.equal(last.game.winner, 'you');
  assert.equal(last.game.hour, 4);
});
