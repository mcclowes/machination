import { createGame } from '../src/game/simulation';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';

test('private prepared launches edit, cancel, and survive restart through seat-scoped hauler commands', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-transport-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'world.json');
  let now = 0;
  let service = await GameService.open(file, () => now, createGame);
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  const created = await service.create(tokens[0]!);
  const other = await service.join(created.invite, tokens[1]!); await service.join(created.invite, tokens[2]!);
  const start = await service.start(created.id, tokens[0]!);
  const queued = await service.gift(created.id, tokens[0]!, { requestId: randomUUID(), revision: start.revision, from: 'c', to: 'f', drones: 20, recipient: 'vesper' });
  const fleet = queued.game.fleets[0]!;
  assert.ok(fleet.preparing);
  const hidden = await service.snapshot(created.id, tokens[1]!);
  assert.equal(hidden.game.fleets.length, 0);
  assert.equal(hidden.revision, other.revision);
  const edit = { requestId: randomUUID(), revision: queued.revision, fleet: fleet.id, action: 'edit-launch' as const, drones: 30 };
  await assert.rejects(() => service.hauler(created.id, tokens[1]!, edit));
  const edited = await service.hauler(created.id, tokens[0]!, edit);
  assert.equal(edited.game.fleets[0]!.drones, 30);
  assert.equal((await service.hauler(created.id, tokens[0]!, edit)).game.fleets[0]!.drones, 30);
  service = await GameService.open(file, () => now, createGame);
  const restored = await service.snapshot(created.id, tokens[0]!);
  const canceled = await service.hauler(created.id, tokens[0]!, { requestId: randomUUID(), revision: restored.revision, fleet: fleet.id, action: 'cancel-launch' });
  assert.equal(canceled.game.fleets.length, 0);
  assert.equal(canceled.game.rocks.find(r => r.id === 'c')!.drones, 40);
  const next = await service.order(created.id, tokens[0]!, { requestId: randomUUID(), revision: canceled.revision, from: 'c', to: 'b', drones: 10 });
  now = 10 * 60_000;
  const departed = await service.snapshot(created.id, tokens[0]!);
  assert.ok(!departed.game.fleets[0]!.preparing);
  await assert.rejects(() => service.hauler(created.id, tokens[0]!, { requestId: randomUUID(), revision: next.revision, fleet: next.game.fleets[0]!.id, action: 'cancel-launch' }));
});
