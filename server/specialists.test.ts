import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { forecastObservation } from '../src/game/visibility';

test('online cores and recruitment use private scoped identities and survive travel, retry, and restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-specialists-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'world.json');
  let now = 0;
  let service = await GameService.open(file, () => now);
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  const created = await service.create(tokens[0]!);
  await service.join(created.invite, tokens[1]!); await service.join(created.invite, tokens[2]!);
  await service.start(created.id, tokens[0]!);
  now = 4 * 3_600_000;
  const start = await service.snapshot(created.id, tokens[0]!);
  const site = start.game.rocks.find(r => r.id === 'a')!; assert.ok(site.known);
  const core = site.specialists!.find(u => u.kind === 'queen')!;
  assert.notEqual(core.id, 'core-you');
  assert.deepEqual(Object.keys(start.game.recruitment!), ['you']);
  assert.equal('seed' in start.game.recruitment!.you!, false);
  await assert.rejects(() => service.order(created.id, tokens[0]!, { requestId: randomUUID(), revision: start.revision, from: 'a', to: 'c', drones: 0, specialists: ['core-you'] }));
  const order = { requestId: randomUUID(), revision: start.revision, from: 'a', to: 'c', drones: 0, specialists: [core.id] };
  const moving = await service.order(created.id, tokens[0]!, order);
  assert.equal((await service.order(created.id, tokens[0]!, order)).game.fleets.length, 1);
  const projected = forecastObservation(moving.game, 'you', 7);
  assert.equal(projected.rocks.find(r => r.id === 'c')!.coreOf, 'you');
  now = 6 * 3_600_000;
  const traveling = await service.snapshot(created.id, tokens[0]!);
  const kind = traveling.game.recruitment!.you!.offers[0]!;
  await assert.rejects(() => service.specialist(created.id, tokens[0]!, { requestId: randomUUID(), revision: traveling.revision, action: 'hire', kind }));
  service = await GameService.open(file, () => now);
  now = 7 * 3_600_000;
  const arrived = await service.snapshot(created.id, tokens[0]!);
  assert.equal(arrived.game.rocks.find(r => r.id === 'c')!.coreOf, 'you');
  const command = { requestId: randomUUID(), revision: arrived.revision, action: 'hire' as const, kind };
  const hired = await service.specialist(created.id, tokens[0]!, command);
  assert.deepEqual((await service.specialist(created.id, tokens[0]!, command)).game.recruitment, hired.game.recruitment);
  const recruited = hired.game.rocks.find(r => r.id === 'c')!; assert.ok(recruited.known);
  assert.ok(recruited.specialists!.some(u => u.kind === kind));
  assert.equal(recruited.specialists!.find(u => u.kind === 'queen')!.id, core.id);
});
