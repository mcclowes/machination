import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { AddressInfo } from 'node:net';
import { GameService } from './service';
import { createApi } from './http';
import { api, historicalApi, messageNotificationsApi } from '../src/online/network';

for (const mode of ['mining', 'domination', 'pulse'] as const) test(`the client decodes real ${mode} lobby, live, history, diplomacy, and notification responses`, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-client-contract-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const service = await GameService.open(join(directory, 'games.json'), () => 0);
  const server = createApi(service);
  await new Promise<void>(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>(resolve => server.close(() => resolve())));
  const url = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const nativeFetch = globalThis.fetch;
  let received: unknown;
  t.mock.method(globalThis, 'fetch', async (...args: Parameters<typeof nativeFetch>) => {
    const response = await nativeFetch(...args);
    received = await response.clone().json();
    return response;
  });
  const host = { url, token: randomBytes(32).toString('hex') }, guest = { url, token: randomBytes(32).toString('hex') };
  const lobby = await api(host, 'games', { options: { playerCount: 2, mode, driftingBases: true, beltCompact: true } });
  assert.equal(lobby.status, 'game.lobby'); assert.deepEqual(lobby.members, ['you']);
  const joined = await api(guest, 'join', { invite: lobby.invite });
  assert.equal(joined.faction, 'vesper');
  const seat = { ...host, id: lobby.id }, path = `games/${lobby.id}`;
  let live = await api(seat, `${path}/start`, {});
  assert.equal(live.status, 'game.active');
  const group = await api(seat, `${path}/groups`, { requestId: randomUUID(), name: 'Pact', members: ['you', 'vesper'] });
  const channelId = group.groups![0]!.id;
  live = await api(seat, `${path}/channel-messages`, { requestId: randomUUID(), channelId, text: 'Private channel' });
  assert.equal(live.channels!.find(channel => channel.id === channelId)!.messages[0]!.text, 'Private channel');
  await api({ ...guest, id: lobby.id }, `${path}/messages`, { requestId: randomUUID(), to: 'you', text: 'Bilateral message' });
  live = await api(seat, path);
  assert.equal(live.messages[0]!.text, 'Bilateral message');
  const source = live.game.rocks.find(rock => rock.owner === 'you' && (rock.drones ?? 0) > 0)!;
  const target = live.game.rocks.find(rock => rock.owner === 'you' && rock.id !== source.id)!;
  live = await api(seat, `${path}/orders`, { requestId: randomUUID(), revision: live.revision, from: source.id, to: target.id, drones: 1 });
  assert.equal(live.game.fleets.length, 1);
  live = await api(seat, `${path}/schedules`, { requestId: randomUUID(), revision: live.revision, executeAt: 1, from: source.id, to: target.id, drones: 1 });
  const kind = live.game.recruitment!.you!.offers[0]!;
  live = await api(seat, `${path}/schedules`, { requestId: randomUUID(), revision: live.revision, executeAt: 2, action: { type: 'hire', kind } });
  live = await api(seat, `${path}/schedules`, { requestId: randomUUID(), revision: live.revision, executeAt: 3, action: { type: 'shields', rock: source.id, disabled: true } });
  assert.equal(live.game.scheduled.length, 3);
  assert.deepEqual(live, received, 'live decoding preserves the complete wire response');
  const history = await historicalApi(seat, 0);
  assert.deepEqual(history, received, 'historical decoding preserves its own wire response');
  const settings = await messageNotificationsApi(seat, 'a'.repeat(64));
  assert.equal(settings.enabled, false); assert.equal(settings.available, false);
});
