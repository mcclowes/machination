import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { forecastObservation } from '../src/game/visibility';

test('authoritative industry, mine construction, and shield controls persist and authorize by seat', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-economy-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'world.json');
  let now = 0;
  let service = await GameService.open(file, () => now);
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  const created = await service.create(tokens[0]!);
  await service.join(created.invite, tokens[1]!); await service.join(created.invite, tokens[2]!);
  const started = await service.start(created.id, tokens[0]!);
  assert.equal(started.game.version, 2);
  const predicted = forecastObservation(started.game, 'you', 16);
  assert.equal(predicted.rocks.find(r => r.id === 'c')!.drones, 52);
  now = 16 * 3_600_000;
  const current = await service.snapshot(created.id, tokens[0]!);
  const command = { requestId: randomUUID(), revision: current.revision, rock: 'c', action: 'mine' as const };
  await assert.rejects(() => service.site(created.id, tokens[1]!, command));
  const mined = await service.site(created.id, tokens[0]!, command);
  assert.equal(mined.game.rocks.find(r => r.id === 'c')!.drones, 2);
  assert.equal(mined.game.rocks.find(r => r.id === 'c')!.kind, 'mine');
  assert.equal((await service.site(created.id, tokens[0]!, command)).game.minesDrilled!.you, 1);
  const toggled = await service.site(created.id, tokens[0]!, { requestId: randomUUID(), revision: mined.revision, rock: 'c', action: 'shields', disabled: true });
  const toggledSite = toggled.game.rocks.find(r => r.id === 'c')!;
  assert.ok(toggledSite.known);
  assert.equal(toggledSite.shieldsDisabled, true);
  service = await GameService.open(file, () => now);
  now = 40 * 3_600_000;
  const restored = await service.snapshot(created.id, tokens[0]!);
  assert.equal(restored.game.cargo.you, 5);
  const restoredSite = restored.game.rocks.find(r => r.id === 'c')!;
  assert.ok(restoredSite.known);
  assert.equal(restoredSite.shieldsDisabled, true);
  assert.equal(restored.game.minesDrilled!.you, 1);
  assert.deepEqual((await service.snapshot(created.id, tokens[1]!)).game.minesDrilled, { vesper: 0 });
});
