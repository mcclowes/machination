import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { temporalWorld } from '../src/game/temporal-test-world';
import { validObservation } from '../src/game/observation-format';

test('online temporal activation authorizes scoped identities, retries once, and survives restart with repayment intact', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-temporal-service-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'rooms.json');
  let now = 0;
  const factory = () => {
    const game = temporalWorld();
    Object.assign(game.rocks[1]!, { kind: 'factory', productionAt: 32, productionInterval: 8 });
    game.rocks[1]!.specialists!.push({ id: 'private-overclock-unit', kind: 'overclock', owner: 'you' });
    return game;
  };
  let service = await GameService.open(file, () => now, factory);
  const [host, guest] = Array.from({ length: 2 }, () => randomBytes(32).toString('hex')) as [string, string];
  const room = await service.create(host);
  await service.join(room.invite, guest);
  const started = await service.start(room.id, host);
  const unit = started.game.rocks.flatMap(r => r.specialists ?? []).find(u => u.kind === 'overclock')!;
  assert.notEqual(unit.id, 'private-overclock-unit');
  await assert.rejects(() => service.specialist(room.id, host, { requestId: randomUUID(), revision: started.revision, action: 'activate', unit: 'private-overclock-unit' }), /controlled site/i);
  const enemy = await service.snapshot(room.id, guest);
  await assert.rejects(() => service.specialist(room.id, guest, { requestId: randomUUID(), revision: enemy.revision, action: 'activate', unit: unit.id }), /controlled site/i);
  const command = { requestId: randomUUID(), revision: started.revision, action: 'activate' as const, unit: unit.id };
  const boosted = await service.specialist(room.id, host, command);
  assert.equal(validObservation(boosted.game), true);
  const boostedSite = boosted.game.rocks.find(r => r.id === 'b')!; assert.ok(boostedSite.known);
  assert.equal(boostedSite.overclock?.boostUntil, 28);
  assert.deepEqual((await service.specialist(room.id, host, command)).game, boosted.game);
  service = await GameService.open(file, () => now, factory);
  now = 29 * 3_600_000;
  const repaying = await service.snapshot(room.id, host);
  const site = repaying.game.rocks.find(r => r.id === 'b')!;
  assert.ok(site.known);
  assert.equal(site.overclock?.repaying, true);
  assert.equal(site.drones, 46);
  const historical = await service.history(room.id, host, 24);
  assert.equal(validObservation(historical.game), true);
  const historicalSite = historical.game.rocks.find(r => r.id === 'b')!; assert.ok(historicalSite.known);
  assert.equal(historicalSite.overclock?.boostUntil, 28);
});
