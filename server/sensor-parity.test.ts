import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { AddressInfo } from 'node:net';
import { createGame, type Fleet } from '../src/game/simulation';
import { forecastObservation } from '../src/game/visibility';
import type { Snapshot } from '../src/online/protocol';
import { GameService } from './service';
import { createApi } from './http';

test('v2 HTTP snapshots scope remote incoming ships, private preparation, unknown types, and identities per seat', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-sensor-parity-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'games.json');
  const initial = () => {
    const game = createGame(0);
    game.rocks = game.rocks.map(r => ({ ...r, x: r.owner === 'you' ? 0 : r.owner === 'null' ? 400 : 200, y: 0 }));
    game.rocks.find(r => r.id === 'j')!.kind = 'mine';
    game.rocks.find(r => r.id === 'j')!.miningAt = 24;
    const ship = (id: number, extra: Partial<Fleet>): Fleet => ({ id, from: 'e', to: 'a', owner: 'vesper', specialists: [], drones: 7, departed: 0, arrives: 30, route: { from: { x: 200, y: 0 }, to: { x: 0, y: 0 } }, ...extra });
    game.fleets = [ship(1, { owner: 'you', to: 'e' }), ship(2, { specialists: [{ id: 'remote-pirate', owner: 'vesper', kind: 'pirate' }], lastContacts: [{ id: 1, hour: 0 }] }), ship(3, { preparing: true, departed: 1 / 6 }), ship(4, { to: 'e', specialists: [{ id: 'intercept-pirate', owner: 'vesper', kind: 'pirate' }], intercept: { home: 'e', target: 1 } }), ship(5, { to: 'g' })];
    game.nextId = 6;
    return game;
  };
  const service = await GameService.open(file, () => 0, initial);
  const tokens = ['a'.repeat(64), 'b'.repeat(64)];
  const created = await service.create(tokens[0]!);
  await service.join(created.invite, tokens[1]!);
  const api = createApi(service);
  await new Promise<void>(resolve => api.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>((resolve, reject) => api.close(error => error ? reject(error) : resolve())));
  const base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1/games/${created.id}`;
  const read = async (seat: number) => {
    const response = await fetch(`${base}?faction=vesper&visibility=all&forecast=24`, { headers: { Authorization: `Bearer ${tokens[seat]}` } });
    assert.equal(response.status, 200);
    return await response.json() as Snapshot;
  };
  const you = await read(0);
  const enemy = await read(1);
  assert.equal(you.faction, 'you');
  assert.equal(you.game.hour, 0);
  assert.equal(you.game.fleets.length, 3);
  assert.equal(enemy.game.fleets.length, 5);
  const remote = you.game.fleets.find(f => f.specialists?.length)!;
  const otherRemote = enemy.game.fleets.find(f => f.specialists?.some(u => u.kind === 'pirate'))!;
  assert.notEqual(remote.id, otherRemote.id);
  assert.notEqual(remote.specialists![0]!.id, otherRemote.specialists![0]!.id);
  assert.ok(!('lastContacts' in remote));
  assert.equal(you.game.fleets.find(f => f.intercept)!.intercept!.target, you.game.fleets.find(f => f.owner === 'you')!.id);
  const hidden = you.game.rocks.find(r => r.id === 'e')!;
  assert.deepEqual(Object.keys(hidden).sort(), ['id', 'kind', 'known', 'name', 'x', 'y']);
  assert.equal(hidden.kind, 'unknown');
  assert.equal(you.game.rocks.find(r => r.id === 'j')!.kind, 'mine');
  assert.deepEqual(you.game.cargo, { you: 0 });
  const original = structuredClone(you);
  forecastObservation(you.game, 'you', 1);
  assert.deepEqual(you, original);
  const restarted = await GameService.open(file, () => 0, initial);
  assert.deepEqual(await restarted.snapshot(created.id, tokens[0]!), you);
});
