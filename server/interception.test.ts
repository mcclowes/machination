import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { GameService } from './service';
import { createApi } from './http';
import type { Snapshot } from '../src/online/protocol';

test('HTTP interception requires an observed seat-scoped target and survives retries and restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-intercept-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'games.json');
  let now = 0;
  let api = createApi(await GameService.open(file, () => now));
  const listen = () => new Promise<void>(resolve => api.listen(0, '127.0.0.1', resolve));
  const close = () => new Promise<void>((resolve, reject) => api.close(e => e ? reject(e) : resolve()));
  await listen(); t.after(close);
  let base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1`;
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  async function request(path: string, seat: number, body?: unknown) {
    const response = await fetch(`${base}/${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${tokens[seat]}`, 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() as Snapshot };
  }
  const created = (await request('games', 0, {})).data;
  const path = `games/${created.id}`;
  const vesper = (await request('join', 1, { invite: created.invite })).data;
  await request('join', 2, { invite: created.invite });
  const started = (await request(`${path}/start`, 0, {})).data;
  const equipped = (await request(`${path}/modules`, 0, { requestId: randomUUID(), revision: started.revision, rock: 'a', module: 'scavenger' })).data;
  const sent = (await request(`${path}/orders`, 1, { requestId: randomUUID(), revision: vesper.revision, from: 'e', to: 'a', drones: 40 })).data;
  const hidden = { requestId: randomUUID(), revision: equipped.revision, from: 'a', target: sent.game.fleets[0]!.id, drones: 50, requireContact: false };
  assert.equal((await request(`${path}/intercepts`, 0, hidden)).status, 409, 'another seat target ID and client visibility flags cannot bypass sensors');
  now = 4 * 3_600_000;
  const observed = (await request(path, 0)).data;
  const target = observed.game.fleets[0]!.id;
  assert.equal((await request(`${path}/intercepts`, 0, { ...hidden, requestId: randomUUID(), target: 1 })).status, 409, 'raw global IDs are not accepted');
  assert.equal((await request(`${path}/intercepts`, 0, { ...hidden, requestId: randomUUID(), from: 'e', target })).status, 409);
  const command = { requestId: randomUUID(), revision: observed.revision, from: 'a', target, drones: 50 };
  const dispatched = await request(`${path}/intercepts`, 0, command);
  assert.equal(dispatched.status, 200);
  const rig = dispatched.data.game.fleets.find(f => f.intercept)!;
  assert.equal(rig.intercept!.target, target, 'target references use the requesting seat IDs');
  assert.equal(dispatched.data.game.rocks[0]!.drones, 28);
  const duplicate = await request(`${path}/intercepts`, 0, command);
  assert.equal(duplicate.data.game.fleets.filter(f => f.intercept).length, 1);
  assert.equal(duplicate.data.game.rocks[0]!.drones, 28);
  await close();
  api = createApi(await GameService.open(file, () => now)); await listen();
  base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1`;
  assert.deepEqual((await request(path, 0)).data, dispatched.data);
  now = Math.ceil(rig.arrives * 3_600_000);
  const returned = (await request(path, 0)).data;
  assert.equal(returned.game.fleets.length, 1);
  assert.equal(returned.game.fleets[0]!.returning, true);
  assert.equal(returned.game.fleets[0]!.drones, 20);
  assert.equal((await request(`${path}/intercepts`, 0, command)).data.game.fleets.length, 1, 'retry after combat cannot dispatch a second rig');
  now = 8 * 3_600_000;
  const home = (await request(path, 0)).data;
  assert.equal(home.game.fleets.length, 0);
  assert.equal(home.game.rocks[0]!.module, 'scavenger');
  assert.equal(home.game.rocks[0]!.drones, 64);
});
