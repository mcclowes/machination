import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';

test('cargo-paid recruitment is authoritative, retry-safe, historical, and durable', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-cargo-hires-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'world.json');
  let now = 0;
  let service = await GameService.open(file, () => now);
  const host = randomBytes(32).toString('hex'), guest = randomBytes(32).toString('hex');
  const room = await service.create(host, { playerCount: 2, mode: 'mining' });
  await service.join(room.invite, guest);
  await service.start(room.id, host);
  now = 3 * 3_600_000;
  const ready = await service.snapshot(room.id, host);
  assert.equal(ready.game.cargo.you, 5);
  const command = { requestId: randomUUID(), revision: ready.revision, action: 'hire' as const, kind: ready.game.recruitment!.you!.offers[0]! };
  const hired = await service.specialist(room.id, host, command);
  assert.equal(hired.game.cargo.you, 0);
  assert.equal((await service.specialist(room.id, host, command)).game.cargo.you, 0);
  service = await GameService.open(file, () => now);
  assert.equal((await service.specialist(room.id, host, command)).game.cargo.you, 0);
  assert.equal((await service.history(room.id, host, 0)).game.cargo.you, 5);
  assert.equal((await service.history(room.id, host, 3)).game.cargo.you, 0);
  now = 16 * 3_600_000;
  const poor = await service.snapshot(room.id, host);
  assert.equal(poor.game.cargo.you, 4);
  const next = { requestId: randomUUID(), revision: poor.revision, action: 'hire' as const, kind: poor.game.recruitment!.you!.offers[0]! };
  await assert.rejects(() => service.specialist(room.id, host, next), /5 cargo/);
  const unchanged = await service.snapshot(room.id, host);
  assert.equal(unchanged.revision, poor.revision);
  assert.deepEqual(unchanged.game.recruitment, poor.game.recruitment);
  now = 20 * 3_600_000;
  const funded = await service.snapshot(room.id, host);
  assert.equal(funded.game.cargo.you, 5);
  const retried = await service.specialist(room.id, host, { ...next, revision: funded.revision });
  assert.equal(retried.game.cargo.you, 0);
  assert.equal(retried.game.recruitment!.you!.used, 2);
});
