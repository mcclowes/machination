import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { createConfiguredGame } from '../src/game/world';
import { advance } from '../src/game/simulation';
import { forecastObservation } from '../src/game/visibility';

for (const martyr of [false, true]) test(`authoritative mine ${martyr ? 'destruction' : 'capture'} preserves scoped rules, replay, and restart`, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-mine-loss-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'world.json'); let now = 0;
  const initial = () => {
    const game = createConfiguredGame({ playerCount: 2, mode: 'mining' }, 0, 10);
    for (const rock of game.rocks) Object.assign(rock, { x: 50, y: 0 });
    const source = game.rocks.find(r => r.owner === 'you' && !r.coreOf)!;
    const mine = game.rocks.find(r => r.owner === 'vesper' && !r.coreOf)!;
    Object.assign(source, { x: 10, y: 50, drones: 100 });
    if (martyr) source.specialists!.push({ id: 'server-martyr', kind: 'martyr', owner: 'you' });
    Object.assign(mine, { x: 18, y: 50, kind: 'mine', drones: 0, shield: 0, miningAt: 24 });
    game.cargo.vesper = 11;
    return advance(game, 0);
  };
  let service = await GameService.open(file, () => now, initial);
  const tokens = [randomBytes(32).toString('hex'), randomBytes(32).toString('hex')];
  const room = await service.create(tokens[0]!); await service.join(room.invite, tokens[1]!);
  const started = await service.start(room.id, tokens[0]!);
  assert.equal(started.game.rules!.mechanicsVersion, 4);
  const source = started.game.rocks.find(r => r.owner === 'you' && r.x === 10)!;
  const mine = started.game.rocks.find(r => r.owner === 'vesper' && r.x === 18)!;
  const order = { requestId: randomUUID(), revision: started.revision, from: source.id, to: mine.id, drones: 10, specialists: source.specialists!.map(u => u.id) };
  const launched = await service.order(room.id, tokens[0]!, order);
  assert.equal((await service.order(room.id, tokens[0]!, order)).game.fleets.length, 1);
  const arrival = launched.game.fleets[0]!.arrives;
  const forecast = forecastObservation(launched.game, 'you', arrival);
  now = arrival * 3_600_000;
  const result = await service.snapshot(room.id, tokens[1]!);
  const host = await service.snapshot(room.id, tokens[0]!);
  const target = host.game.rocks.find(r => r.id === mine.id)!;
  assert.equal(target.owner, martyr ? 'vesper' : 'you');
  assert.equal(target.destroyed, martyr ? true : undefined);
  assert.equal(result.game.cargo.vesper, martyr ? 11 : 8);
  assert.equal(forecast.rocks.find(r => r.id === mine.id)!.destroyed, target.destroyed);
  if (martyr) await assert.rejects(() => service.site(room.id, tokens[1]!, { requestId: randomUUID(), revision: result.revision, rock: mine.id, action: 'shields', disabled: true }));
  const past = await service.history(room.id, tokens[1]!, 0);
  assert.equal(past.game.rocks.find(r => r.id === mine.id)!.destroyed, undefined);
  assert.equal(past.game.cargo.vesper, 11);
  service = await GameService.open(file, () => now, initial);
  assert.deepEqual((await service.snapshot(room.id, tokens[1]!)).game, result.game);
  assert.deepEqual((await service.history(room.id, tokens[1]!, arrival)).game, result.game);
  now = 20 * 3_600_000;
  const later = await service.snapshot(room.id, tokens[1]!);
  assert.equal(later.game.cargo.vesper, martyr ? 11 : 8);
});
