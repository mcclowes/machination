import { createLegacyGame } from '../src/game/legacy';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { GameService } from './service';
import { createApi } from './http';
import type { Snapshot } from '../src/contracts/protocol';

test('every HTTP view filters hidden state, scopes history, and isolates command revisions', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-visibility-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'games.json');
  let now = 0;
  const api = createApi(await GameService.open(file, () => now, createLegacyGame));
  await new Promise<void>(resolve => api.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise<void>((resolve, reject) => api.close(e => e ? reject(e) : resolve())));
  const base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1`;
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  async function request(path: string, seat: number, payload?: unknown) {
    const response = await fetch(`${base}/${path}`, { method: payload === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${tokens[seat]}`, 'Content-Type': 'application/json' }, body: payload === undefined ? undefined : JSON.stringify(payload) });
    assert.equal(response.status, 200);
    return await response.json() as Snapshot;
  }
  const created = await request('games', 0, {});
  assert.equal(created.visibility, 'sensors.v1');
  assert.equal(created.game.rocks[4]!.known, false);
  const vesper = await request('join', 1, { invite: created.invite });
  await request('join', 2, { invite: created.invite });
  const path = `games/${created.id}`;
  const started = await request(`${path}/start`, 0, {});
  const equipped = await request(`${path}/modules`, 1, { requestId: randomUUID(), revision: vesper.revision, rock: 'e', module: 'routing' });
  const dispatched = await request(`${path}/orders`, 1, { requestId: randomUUID(), revision: equipped.revision, from: 'e', to: 'a', drones: 30, carryModule: true });
  const hidden = await request(path, 0);
  assert.equal(hidden.revision, started.revision, 'opponent activity cannot increment my command revision');
  assert.equal(hidden.game.fleets.length, 0);
  assert.deepEqual(hidden.game.cargo, { you: 0 });
  for (const key of ['owner', 'drones', 'module', 'coreOf']) assert.ok(!(key in hidden.game.rocks[4]!));
  assert.ok(!('nextId' in hidden.game));
  assert.ok(!hidden.game.events.some(e => e.message.includes('constructed') || e.message.includes('dispatched')));
  assert.equal(dispatched.game.fleets[0]!.module, 'routing', 'actor sees its own module manifest');
  const scout = await request(`${path}/orders`, 0, { requestId: randomUUID(), revision: hidden.revision, from: 'a', to: 'e', drones: 1 });
  assert.equal(scout.game.fleets.length, 1, 'own haulers are visible even on hidden routes');
  now = 3 * 3_600_000;
  const contact = await request(path, 0);
  const enemyView = await request(path, 1);
  assert.equal(contact.game.fleets.length, 2, 'incoming hauler enters sensor coverage');
  const enemyFleet = contact.game.fleets.find(f => f.owner === 'vesper')!;
  assert.equal(enemyFleet.module, 'routing');
  assert.notEqual(enemyFleet.id, 1, 'global launch sequence is not a public ID');
  assert.notEqual(enemyFleet.id, enemyView.game.fleets.find(f => f.owner === 'vesper')!.id, 'hauler IDs are scoped to a seat');
  assert.ok(!contact.game.events.some(e => e.message.includes('Routing daemon constructed')));
  const spoofed = await request(`${path}?faction=vesper&visibility=all&forecast=24`, 0);
  assert.equal(spoofed.faction, 'you');
  assert.equal(spoofed.game.rocks[4]!.known, false);
  assert.equal(spoofed.game.hour, 3, 'query flags cannot reveal a future authoritative state');
  await request(`${path}/messages`, 1, { requestId: randomUUID(), to: 'null', text: 'Hidden bilateral transmission.' });
  const privateReply = await request(`${path}/messages`, 0, { requestId: randomUUID(), to: 'vesper', text: 'My transmission.' });
  assert.equal(privateReply.game.rocks[4]!.known, false, 'message responses use the same sensor filter');
  assert.equal(privateReply.messages.length, 1);
  assert.notEqual(privateReply.messages[0]!.id, 2, 'private-message IDs do not reveal a global message count');
  assert.ok(!JSON.stringify(privateReply).includes('Hidden bilateral transmission.'));
  now = 6 * 3_600_000;
  const scouted = await request(path, 0);
  assert.equal(scouted.game.rocks[4]!.known, true, 'mobile sensor reveals distant station');
  assert.equal(scouted.game.rocks[4]!.owner, 'vesper');
  assert.ok(!scouted.game.events.some(e => e.message.includes('Routing daemon constructed')), 'old hidden events remain hidden after discovery');
  now = 8 * 3_600_000;
  const lost = await request(path, 0);
  assert.equal(lost.game.rocks[4]!.known, false, 'scout destruction ends remote visibility');
  assert.equal(lost.revision, scout.revision);
  const restarted = await GameService.open(file, () => now, createLegacyGame);
  assert.deepEqual(await restarted.snapshot(created.id, tokens[0]!), lost, 'visibility and seat revisions survive restart');
});
