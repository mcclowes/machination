import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { createPreCargoGame as createConfiguredGame } from '../src/game/test-world';

test('pending Navigator orders are private, retryable, cancelable, and retained through server restart', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-navigator-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'world.json'); let now = 0;
  let sourceId = '', targetId = '', destinationId = '';
  const initial = () => {
    const game = createConfiguredGame({ playerCount: 2, mode: 'mining' }, 0, 73);
    game.rules!.map.width = 200; game.rules!.map.height = 200;
    for (const rock of game.rocks) { rock.productionAt = 1000; rock.shieldAt = 1000; }
    const source = game.rocks.find(r => r.owner === 'you' && !r.coreOf)!;
    const target = game.rocks.find(r => r.owner === 'vesper' && !r.coreOf)!;
    const destination = game.rocks.find(r => r.owner === null)!;
    sourceId = source.id; targetId = target.id; destinationId = destination.id;
    Object.assign(source, { x: 20, y: 20 }); Object.assign(target, { x: 68, y: 20 }); Object.assign(destination, { x: 20, y: 100 });
    source.specialists!.push({ id: 'server-delayed-nav', owner: 'you', kind: 'navigator' });
    return game;
  };
  let service = await GameService.open(file, () => now, initial);
  const host = randomBytes(32).toString('hex'), guest = randomBytes(32).toString('hex');
  const room = await service.create(host); await service.join(room.invite, guest); await service.start(room.id, host);
  now = 11 * 3_600_000;
  const ready = await service.snapshot(room.id, host);
  const unit = ready.game.rocks.find(r => r.id === sourceId)!.specialists!.find(u => u.kind === 'navigator')!;
  const sent = await service.order(room.id, host, { requestId: randomUUID(), revision: ready.revision, from: sourceId, to: targetId, drones: 10, specialists: [unit.id] });
  now = 11.5 * 3_600_000;
  const moving = await service.snapshot(room.id, host);
  const id = sent.game.fleets[0]!.id;
  const request = { requestId: randomUUID(), revision: moving.revision, fleet: id, action: 'course' as const, to: destinationId };
  const ordered = await service.hauler(room.id, host, request);
  assert.equal(ordered.game.fleets[0]!.to, targetId);
  assert.equal(ordered.game.fleets[0]!.pendingCourse!.to, destinationId);
  assert.deepEqual((await service.hauler(room.id, host, request)).game, ordered.game);
  const foreign = await service.snapshot(room.id, guest);
  assert.equal(foreign.game.fleets.length, 1);
  assert.equal(foreign.game.fleets[0]!.pendingCourse, undefined);
  assert.ok(!foreign.game.events.some(e => e.message.startsWith('Course change ordered.')));
  await assert.rejects(() => service.hauler(room.id, guest, { requestId: randomUUID(), revision: foreign.revision, fleet: foreign.game.fleets[0]!.id, action: 'cancel-course' }));
  const canceled = await service.hauler(room.id, host, { requestId: randomUUID(), revision: ordered.revision, fleet: id, action: 'cancel-course' });
  assert.equal(canceled.game.fleets[0]!.pendingCourse, undefined);
  const again = await service.hauler(room.id, host, { ...request, requestId: randomUUID(), revision: canceled.revision });
  service = await GameService.open(file, () => now, initial);
  assert.deepEqual((await service.snapshot(room.id, host)).game, again.game);
  assert.ok((await service.history(room.id, host, 11.5)).game.fleets[0]!.pendingCourse);
  assert.equal((await service.history(room.id, guest, 11.5)).game.fleets[0]!.pendingCourse, undefined);
  now = again.game.fleets[0]!.pendingCourse!.executeAt * 3_600_000;
  const turned = await service.snapshot(room.id, host);
  assert.equal(turned.game.fleets[0]!.pendingCourse, undefined);
  assert.equal(turned.game.fleets[0]!.to, destinationId);
  service = await GameService.open(file, () => now, initial);
  assert.deepEqual((await service.snapshot(room.id, host)).game, turned.game);
});
