import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { GameService } from './service';
import { createApi } from './http';
import type { Snapshot } from '../src/online/protocol';

test('HTTP plans remain private, cancel safely, and execute exactly once across a server restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-orders-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'games.json');
  let now = 0;
  let api = createApi(await GameService.open(file, () => now));
  const listen = () => new Promise<void>(resolve => api.listen(0, '127.0.0.1', resolve));
  const close = () => new Promise<void>((resolve, reject) => api.close(e => e ? reject(e) : resolve()));
  await listen(); t.after(close);
  let base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1`;
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  async function request(path: string, seat: number, payload?: unknown) {
    const response = await fetch(`${base}/${path}`, { method: payload === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${tokens[seat]}`, 'Content-Type': 'application/json' }, body: payload === undefined ? undefined : JSON.stringify(payload) });
    return { status: response.status, data: await response.json() as Snapshot };
  }
  const created = (await request('games', 0, {})).data;
  const path = `games/${created.id}`;
  const plan = { requestId: randomUUID(), revision: 0, from: 'a', to: 'b', drones: 100, executeAt: 3 };
  assert.equal((await request(`${path}/schedules`, 0, plan)).status, 409);
  const vesper = (await request('join', 1, { invite: created.invite })).data;
  await request('join', 2, { invite: created.invite });
  const started = (await request(`${path}/start`, 0, {})).data;
  plan.revision = started.revision;
  const queued = await request(`${path}/schedules`, 0, plan);
  assert.equal(queued.status, 200);
  assert.equal(queued.data.game.rocks[0]!.drones, 90, 'scheduling does not reserve drones');
  assert.equal(queued.data.game.scheduled.length, 1);
  assert.equal((await request(`${path}/schedules`, 0, plan)).data.game.scheduled.length, 1);
  assert.equal((await request(`${path}/schedules`, 0, { ...plan, drones: 101 })).status, 409);
  const enemy = (await request(path, 1)).data;
  assert.equal(enemy.revision, vesper.revision);
  assert.equal(enemy.game.scheduled.length, 0);
  assert.ok(!enemy.game.events.some(e => e.message.includes('Transfer planned')));
  assert.equal((await request(`${path}/cancel-schedule`, 1, { requestId: randomUUID(), revision: enemy.revision, planId: plan.requestId })).status, 409);
  const cancellation = { requestId: randomUUID(), revision: queued.data.revision, planId: plan.requestId };
  const canceled = await request(`${path}/cancel-schedule`, 0, cancellation);
  assert.equal(canceled.status, 200);
  assert.equal(canceled.data.game.scheduled.length, 0);
  assert.equal((await request(`${path}/cancel-schedule`, 0, cancellation)).status, 200);
  now = 3_600_000;
  assert.equal((await request(path, 0)).data.game.fleets.length, 0);
  const nextPlan = { ...plan, requestId: randomUUID(), revision: canceled.data.revision };
  const pending = await request(`${path}/schedules`, 0, nextPlan);
  assert.equal(pending.status, 200);
  await close();
  api = createApi(await GameService.open(file, () => now));
  await listen();
  base = `http://127.0.0.1:${(api.address() as AddressInfo).port}/v1`;
  assert.equal((await request(path, 0)).data.game.scheduled.length, 1);
  now = 3 * 3_600_000;
  const launched = (await request(path, 0)).data;
  assert.equal(launched.game.fleets.length, 1);
  assert.equal(launched.game.fleets[0]!.departed, 3);
  assert.equal(launched.game.rocks[0]!.drones, 2);
  assert.equal(launched.game.scheduled.length, 0);
  assert.equal((await request(`${path}/schedules`, 0, nextPlan)).data.game.fleets.length, 1, 'old retry cannot reschedule a launched plan');
  assert.equal((await request(`${path}/cancel-schedule`, 0, { requestId: randomUUID(), revision: launched.revision, planId: nextPlan.requestId })).status, 409);
  now = 6 * 3_600_000;
  const arrived = (await request(path, 0)).data;
  assert.equal(arrived.game.rocks[1]!.owner, 'you');
  assert.equal(arrived.game.fleets.length, 0);
});
