import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { GameService } from './service';
import { createApi } from './http';
import { councilBallots } from '../src/game/compact';
import { decodeSharedReplay } from '../src/replay/codec';

test('public ballots are authorized, idempotent, replayable, and durable through daily resolution', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-council-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'state.json'); let now = 0;
  let service = await GameService.open(file, () => now);
  const tokens = Array.from({ length: 3 }, () => randomBytes(32).toString('hex'));
  const lobby = await service.create(tokens[0]!, { playerCount: 3, mode: 'mining', beltCompact: true });
  for (const token of tokens.slice(1)) await service.join(lobby.invite, token);
  const vote = { requestId: randomUUID(), action: 'vote', motionId: 1, choice: 'yes' };
  await assert.rejects(() => service.council(lobby.id, tokens[0]!, vote), /not started/);
  await service.start(lobby.id, tokens[0]!);
  await assert.rejects(() => service.council(lobby.id, randomBytes(32).toString('hex'), vote), /token/);
  const first = await service.council(lobby.id, tokens[0]!, vote);
  assert.equal(first.game.compact!.motion!.changes.length, 1);
  assert.deepEqual((await service.council(lobby.id, tokens[0]!, vote)).game.compact, first.game.compact);
  await assert.rejects(() => service.council(lobby.id, tokens[0]!, { ...vote, choice: 'no' }), /different content/);
  await service.council(lobby.id, tokens[1]!, { ...vote, requestId: randomUUID() });
  await service.council(lobby.id, tokens[0]!, { requestId: randomUUID(), action: 'nominate', motionId: 1, policy: 'salvage' });
  await service.council(lobby.id, tokens[1]!, { requestId: randomUUID(), action: 'nominate', motionId: 1, policy: 'weapons' });
  const observer = await service.snapshot(lobby.id, tokens[2]!);
  assert.deepEqual(councilBallots(observer.game.compact!.motion!), { you: 'yes', vesper: 'yes' });
  assert.equal(observer.game.compact!.proposals.vesper, 'weapons');
  service = await GameService.open(file, () => now);
  now = 24 * 3_600_000;
  const resolved = await service.snapshot(lobby.id, tokens[0]!);
  assert.equal(resolved.game.compact!.history[0]!.result, 'passed');
  assert.equal(resolved.game.compact!.waivers.transit!.expiresAt, 72);
  assert.equal(resolved.game.compact!.motion!.policy, 'weapons');
  assert.equal(resolved.game.compact!.motion!.proposer, 'vesper');
  assert.equal(resolved.game.compact!.proposals.you, 'salvage');
  assert.equal((await service.council(lobby.id, tokens[0]!, vote)).game.compact!.history.length, 1, 'lost-response retries remain valid after the ballot closes');
  await assert.rejects(() => service.council(lobby.id, tokens[0]!, { ...vote, requestId: randomUUID() }), /closed/);
  await assert.rejects(() => service.council(lobby.id, tokens[0]!, { requestId: randomUUID(), action: 'nominate', motionId: 1, policy: 'sensors' }), /agenda/);
  const historical = await service.history(lobby.id, tokens[0]!, 23);
  assert.equal(historical.game.compact!.motion!.id, 1);
  assert.equal(historical.game.compact!.waivers.transit, undefined);
  const stored = JSON.parse(await readFile(file, 'utf8'));
  const corrupt = structuredClone(stored); corrupt.rooms[0].game.compact.motion.policy = 'invented';
  await writeFile(join(dir, 'corrupt.json'), JSON.stringify(corrupt));
  await assert.rejects(() => GameService.open(join(dir, 'corrupt.json'), () => now), /save/);
  service = await GameService.open(file, () => now);
  assert.deepEqual((await service.snapshot(lobby.id, tokens[2]!)).game.compact, resolved.game.compact);
  const shared = await service.sharedReplay(lobby.id, tokens[0]!, 0, 24);
  assert.ok(decodeSharedReplay(JSON.stringify(shared)));
  now = 47 * 3_600_000;
  for (const token of tokens) await service.activity(lobby.id, token);
  now = 72 * 3_600_000;
  const caughtUp = await service.snapshot(lobby.id, tokens[0]!);
  assert.equal(caughtUp.game.compact!.history.length, 3);
  assert.equal(caughtUp.game.compact!.waivers.transit, undefined);
  service = await GameService.open(file, () => now);
  assert.equal((await service.snapshot(lobby.id, tokens[0]!)).game.compact!.motion!.id, 4);
});

test('HTTP council decoding rejects malformed commands and preserves old operation rules', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-council-http-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const service = await GameService.open(join(dir, 'state.json'), () => 0);
  const server = createApi(service); server.listen(0, '127.0.0.1'); await once(server, 'listening'); t.after(() => { server.closeAllConnections(); server.close(); });
  const address = server.address(); assert.ok(address && typeof address !== 'string');
  const tokens = [randomBytes(32).toString('hex'), randomBytes(32).toString('hex')];
  const room = await service.create(tokens[0]!, { playerCount: 2, mode: 'mining', beltCompact: true });
  await service.join(room.invite, tokens[1]!); await service.start(room.id, tokens[0]!);
  const origin = `http://127.0.0.1:${address.port}`;
  async function post(command: unknown, token = tokens[0]!) {
    return fetch(`${origin}/v1/games/${room.id}/council`, { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify(command) });
  }
  const good = { requestId: randomUUID(), action: 'vote', motionId: 1, choice: 'yes' };
  for (const bad of [{ ...good, choice: 'maybe' }, { ...good, motionId: 0 }, { ...good, owner: 'vesper' }, { ...good, action: 'enforce' }, { requestId: randomUUID(), action: 'nominate', motionId: 1, policy: '__proto__' }]) assert.equal((await post(bad)).status, 400);
  assert.equal((await post(good, randomBytes(32).toString('hex'))).status, 401);
  assert.equal((await post(good)).status, 200);
  assert.equal((await post(good)).status, 200);
  assert.equal((await post({ ...good, choice: 'no' })).status, 409);
  const legacy = await service.create(randomBytes(32).toString('hex'), { playerCount: 2, mode: 'mining' });
  assert.equal(legacy.game.compact, undefined);
  await assert.rejects(() => service.create(tokens[0]!, { playerCount: 2, mode: 'mining', beltCompact: false }), /different settings/);
});
