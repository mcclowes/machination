import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { randomUUID } from 'node:crypto';
import { GameService } from './service';
import { forecastObservation } from '../src/game/visibility';
import { generateSharedReplay } from '../src/replay/generate';
import { decodeReplay } from '../src/game/replay-save';
import { decodeSharedReplay, encodeSharedReplay } from '../src/replay/codec';
import { type Game } from '../src/game/simulation';
import { snapshotResponse, historicalResponse } from '../src/online/snapshot-response';

for (const format of ['2v2', '4v4', '3v3v3'] as const) test(`${format}: authenticated seats share plans without command authority, retain history and restart`, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-teams-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'world.json'); let now = 1000;
  let service = await GameService.open(file, () => now);
  const count = format === '2v2' ? 4 : format === '4v4' ? 8 : 9, opponent = format === '2v2' ? 2 : format === '4v4' ? 4 : 3;
  const credentials = Array.from({ length: count }, (_, i) => ({ accountId: `user_TeamSeat${i}` }));
  const options = { playerCount: count, mode: 'mining', teamFormat: format };
  const room = await service.create(credentials[0]!, options);
  await assert.rejects(() => service.create(credentials[0]!, { playerCount: count, mode: 'mining' }));
  await assert.rejects(() => service.start(room.id, credentials[0]!));
  for (let i = 1; i < count; i++) await service.join(room.invite, credentials[i]!);
  await assert.rejects(() => service.start(room.id, credentials[1]!));
  await service.start(room.id, credentials[0]!);
  let own = await service.snapshot(room.id, credentials[0]!);
  let ally = await service.snapshot(room.id, credentials[1]!);
  const enemyBefore = await service.snapshot(room.id, credentials[opponent]!);
  const source = ally.game.rocks.find(r => r.owner === ally.faction && r.known && !r.coreOf && r.drones >= 3)!;
  const destination = ally.game.rocks.find(r => r.owner === ally.faction && r.known && r.coreOf)!;
  assert.ok(own.game.rocks.find(r => r.id === source.id)!.known);
  ally = await service.schedule(room.id, credentials[1]!, { requestId: randomUUID(), revision: ally.revision, from: source.id, to: destination.id, drones: 3, executeAt: 1 });
  own = await service.snapshot(room.id, credentials[0]!);
  assert.deepEqual(snapshotResponse(room.id, own), own);
  assert.equal(own.game.scheduled.length, 1); assert.equal(own.game.scheduled[0]!.owner, ally.faction);
  const enemyAfter = await service.snapshot(room.id, credentials[opponent]!);
  assert.deepEqual(enemyAfter.game, enemyBefore.game);
  const plan = own.game.scheduled[0]!;
  await assert.rejects(() => service.cancelSchedule(room.id, credentials[0]!, { requestId: randomUUID(), revision: own.revision, planId: plan.id }));
  await assert.rejects(() => service.editSchedule(room.id, credentials[0]!, { requestId: randomUUID(), revision: own.revision, planId: plan.id, drones: 2 }));
  await assert.rejects(() => service.order(room.id, credentials[0]!, { requestId: randomUUID(), revision: own.revision, from: source.id, to: destination.id, drones: 1 }));
  await assert.rejects(() => service.site(room.id, credentials[0]!, { requestId: randomUUID(), revision: own.revision, action: 'shields', rock: source.id, disabled: true }));
  const forecast = forecastObservation(own.game, own.faction, 1.1);
  assert.ok(forecast.fleets.some(f => f.owner === ally.faction && f.drones === 3));
  const history = await service.history(room.id, credentials[0]!, 0);
  assert.deepEqual(historicalResponse(room.id, 0, history), history);
  assert.deepEqual(history.game.scheduled, own.game.scheduled);
  service = await GameService.open(file, () => now);
  assert.deepEqual((await service.snapshot(room.id, credentials[0]!)).game, own.game);
  now += 1.1 * 3_600_000;
  own = await service.snapshot(room.id, credentials[0]!);
  assert.equal(own.game.scheduled.length, 0);
  assert.ok(own.game.fleets.some(f => f.owner === ally.faction && f.drones === 3));
  service = await GameService.open(file, () => now);
  assert.deepEqual((await service.snapshot(room.id, credentials[0]!)).game, own.game);
  const stored = JSON.parse(await readFile(file, 'utf8')).rooms[0] as { game: Game; replay: unknown };
  const archive = decodeReplay(stored.replay, stored.game, false);
  const shared = generateSharedReplay({ game: stored.game, archive }, own.faction, 0, 1.1);
  const raw = encodeSharedReplay(shared); assert.deepEqual(decodeSharedReplay(raw), shared);
  assert.equal(raw.includes(plan.id), false); assert.equal(raw.includes('user_TeamSeat'), false);
  assert.ok(shared.groups.every(g => g.states.every(s => s.rules!.teams!.format === format)));
});
