import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { advance } from '../src/game/simulation';
import { createConfiguredGame } from '../src/game/world';
import { fleetPosition } from '../src/game/flight';
import { forecastObservation } from '../src/game/visibility';

test('authoritative edge travel, sonar, forecast, and historical reconstruction agree across restart', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'machination-torus-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'world.json'); let now = 1000;
  const initial = () => {
    const game = createConfiguredGame({ playerCount: 2, mode: 'mining' }, now, 4);
    game.rules!.map = { ...game.rules!.map, generator: 'balanced.v2', topology: 'torus' };
    const size = game.rules!.map.width;
    for (const rock of game.rocks) Object.assign(rock, { x: size / 2, y: 0 });
    const source = game.rocks.find(r => r.owner === 'you' && !r.coreOf)!;
    const target = game.rocks.find(r => r.owner === 'vesper' && !r.coreOf)!;
    Object.assign(source, { x: 1, y: size / 2, drones: 40 });
    Object.assign(target, { x: size - 3, y: size / 2, drones: 0, shield: 0 });
    return advance(game, 0);
  };
  let service = await GameService.open(file, () => now, initial);
  const tokens = [randomBytes(32).toString('hex'), randomBytes(32).toString('hex')];
  const created = await service.create(tokens[0]!);
  await service.join(created.invite, tokens[1]!);
  const started = await service.start(created.id, tokens[0]!);
  const source = started.game.rocks.find(r => r.owner === 'you' && r.x === 1)!;
  const target = started.game.rocks.find(r => r.owner === 'vesper' && !r.coreOf)!;
  assert.equal(target.known, true);
  assert.equal(started.game.rules!.map.topology, 'torus');
  assert.equal(JSON.stringify(started).includes('"seed"'), false);
  const request = { requestId: randomUUID(), revision: started.revision, from: source.id, to: target.id, drones: 10, carryModule: false };
  const launched = await service.order(created.id, tokens[0]!, request);
  const fleet = launched.game.fleets[0]!;
  assert.ok(Math.abs(fleet.arrives - fleet.departed - 1 / 3) < 1e-9);
  assert.deepEqual((await service.order(created.id, tokens[0]!, request)).game, launched.game);
  const inspectedHour = (fleet.departed + fleet.arrives) / 2;
  const forecast = forecastObservation(launched.game, 'you', inspectedHour);
  now += inspectedHour * 3_600_000;
  const live = await service.snapshot(created.id, tokens[0]!);
  const point = fleetPosition(live.game, live.game.fleets[0]!);
  assert.ok(point.x > live.game.rules!.map.width - 2);
  assert.deepEqual(fleetPosition(forecast, forecast.fleets[0]!), point);
  service = await GameService.open(file, () => now, initial);
  assert.deepEqual((await service.snapshot(created.id, tokens[0]!)).game, live.game);
  now += 0.5 * 3_600_000;
  const arrived = await service.snapshot(created.id, tokens[0]!);
  assert.equal(arrived.game.rocks.find(r => r.id === target.id)!.owner, 'you');
  const past = await service.history(created.id, tokens[0]!, inspectedHour);
  assert.deepEqual(past.game, live.game);
});
