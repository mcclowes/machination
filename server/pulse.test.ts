import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { randomBytes, randomUUID } from 'node:crypto';
import { GameService } from './service';
import { createConfiguredGame } from '../src/game/world';
import { DEFAULT_PULSE_CONFIG } from '../src/game/pulse';

test('pulse commands authenticate seats, persist once, and charge using authoritative server time', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-pulse-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  let now = 0;
  const factory = () => { const game = createConfiguredGame({ playerCount: 2, mode: 'pulse' }, 0, 42); game.cargo.you = 100; return game; };
  const file = join(directory, 'games.json');
  let service = await GameService.open(file, () => now, factory);
  const host = randomBytes(32).toString('hex'), other = randomBytes(32).toString('hex');
  const room = await service.create(host);
  const command = { requestId: randomUUID(), revision: 0, action: 'START_CHARGE' as const };
  await assert.rejects(() => service.pulse(room.id, host, command), /not started/);
  await service.join(room.invite, other);
  const started = await service.start(room.id, host); command.revision = started.revision;
  const charging = await service.pulse(room.id, host, command);
  assert.equal(charging.game.cargo.you, 0);
  assert.equal((await service.pulse(room.id, host, command)).game.cargo.you, 0);
  await assert.rejects(() => service.pulse(room.id, host, { ...command, action: 'CANCEL_CHARGE' }), /different content/);
  await assert.rejects(async () => service.pulse(room.id, other, { ...command, requestId: randomUUID(), revision: (await service.snapshot(room.id, other)).revision }), /Pulse Material/);
  service = await GameService.open(file, () => now, factory);
  now = 6 * 3_600_000;
  const ready = await service.snapshot(room.id, host);
  assert.equal(ready.game.pulse!.kings.find(k => k.factionId === 'you')!.state, 'ready');
  const fired = await service.pulse(room.id, host, { requestId: randomUUID(), revision: ready.revision, action: 'FIRE_PULSE' });
  assert.equal(fired.game.pulse!.pulses.length, 1);
  assert.equal(fired.game.pulse!.pulses[0]!.firedAt, 6);
  assert.ok(!JSON.stringify(fired.game).includes('receipts'));
});
test('server balance overrides apply only to new games and cannot be supplied by clients', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-pulse-config-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  const file = join(directory, 'games.json'), host = randomBytes(32).toString('hex');
  let service = await GameService.open(file, () => 0, undefined, { pulse: { ...DEFAULT_PULSE_CONFIG, chargeDuration: 3, shieldMaxEnergy: 60 } });
  const created = await service.create(host, { playerCount: 2, mode: 'pulse' });
  assert.equal(created.game.rules!.pulse!.chargeDuration, 3);
  assert.ok(Object.values(created.game.pulse!.shields).every(s => s.energy === 60));
  await assert.rejects(() => service.create(randomBytes(32).toString('hex'), { playerCount: 2, mode: 'pulse', pulse: { chargeDuration: 0 } }), /Choose/);
  service = await GameService.open(file, () => 0, undefined, { pulse: { ...DEFAULT_PULSE_CONFIG, chargeDuration: 12 } });
  assert.equal((await service.snapshot(created.id, host)).game.rules!.pulse!.chargeDuration, 3);
});

test('Disruptor commands authorize seat aliases, charge once, and launch after server restart', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'machination-disruptor-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  let now = 0;
  const factory = () => {
    const game = createConfiguredGame({ playerCount: 2, mode: 'pulse' }, 0, 42);
    game.cargo.you = 100;
    game.rocks.find(r => r.coreOf === 'you')!.specialists!.push({ id: 'disruptor-private-id', kind: 'disruptor', owner: 'you' });
    return game;
  };
  const file = join(directory, 'games.json'), host = randomBytes(32).toString('hex'), other = randomBytes(32).toString('hex');
  let service = await GameService.open(file, () => now, factory);
  const room = await service.create(host); await service.join(room.invite, other);
  const started = await service.start(room.id, host);
  const unit = started.game.rocks.flatMap(r => r.specialists ?? []).find(u => u.kind === 'disruptor')!;
  const command = { requestId: randomUUID(), revision: started.revision, action: 'CHARGE_DISRUPTOR' as const, specialistId: unit.id, resourceCost: 20 };
  await assert.rejects(() => service.pulse(room.id, host, { ...command, specialistId: 'disruptor-private-id' }), /observed|Disruptor|module/i);
  await assert.rejects(() => service.pulse(room.id, other, { ...command, requestId: randomUUID(), revision: 0 }), /observed|Disruptor|module/i);
  const charging = await service.pulse(room.id, host, command);
  assert.equal(charging.game.cargo.you, 80);
  assert.equal((await service.pulse(room.id, host, command)).game.cargo.you, 80);
  assert.equal((await service.pulse(room.id, host, { resourceCost: 20, specialistId: unit.id, action: 'CHARGE_DISRUPTOR', revision: command.revision, requestId: command.requestId })).game.cargo.you, 80);
  await assert.rejects(() => service.pulse(room.id, host, { ...command, requestId: randomUUID(), id: randomUUID() } as any), /Choose a pulse command/);
  await assert.rejects(() => service.pulse(room.id, host, { ...command, resourceCost: 25 }), /different content/);
  await assert.rejects(() => service.pulse(room.id, host, { ...command, requestId: randomUUID(), revision: started.revision }), /Refresh/);
  assert.equal((await service.snapshot(room.id, other)).game.pulse!.tactical!.charges.length, 0);
  service = await GameService.open(file, () => now, factory);
  now = .5 * 3_600_000;
  const fired = await service.snapshot(room.id, host);
  assert.equal(fired.game.pulse!.tactical!.waves.length, 1);
  assert.equal(fired.game.pulse!.tactical!.charges.length, 0);
  assert.ok(!JSON.stringify(fired).includes('disruptor-private-id'));
});
